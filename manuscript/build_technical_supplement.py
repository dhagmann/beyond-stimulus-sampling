"""Build the blinded supplement and main-only submission copy from current sources."""

from pathlib import Path
import argparse
import os
import re
import subprocess

import pikepdf

from prepare_blinded import strip_pdf_metadata


HERE = Path(__file__).resolve().parent
SUPPLEMENT = 'beyond_stimulus_sampling_technical_supplement_blinded'
SUBMISSION = 'beyond_stimulus_sampling_submission_blinded'
MARKER = '<!-- BEGIN SUPPORTING MATERIALS: regenerated by build_technical_supplement.py -->'
APPENDIX = '# Study 1 Message Pair {#apx-study1-messages}'


def add_appendix_destinations(path):
    text = subprocess.run(['pdftotext', '-layout', str(path), '-'], check=True,
                          capture_output=True, text=True).stdout.split('\f')
    titles = {'apx-study1-messages': 'Appendix A. Study 1 Message Pair',
              'apx-reference-family': 'Appendix B. Full Messages From the Reference Family',
              'apx-stimulus-audit': 'Appendix C. Example Stimulus Audit'}
    linked = path.with_suffix('.linked.pdf')
    with pikepdf.Pdf.open(path) as pdf:
        destinations = pikepdf.NameTree(pdf.Root.Names.Dests)
        for anchor, title in titles.items():
            matches = [i for i, page in enumerate(text)
                       if re.search(r'(?m)^\s*' + re.escape(title) + r'\s*$', page)]
            assert len(matches) == 1, (anchor, matches)
            destinations[anchor] = pikepdf.Array([pdf.pages[matches[0]].obj, pikepdf.Name('/Fit')])
        pdf.save(linked)
    linked.replace(path)


def render(path):
    env = os.environ.copy()
    env.setdefault('XDG_CACHE_HOME', '/tmp/bss-quarto-cache')
    subprocess.run(['quarto', 'render', path.name, '--to',
                    'pdf' if path.stem == SUPPLEMENT else 'apaquarto-pdf', '--quiet'],
                   cwd=HERE, env=env, check=True)
    clean = path.with_suffix('.metadata-clean.pdf')
    strip_pdf_metadata(path.with_suffix('.pdf'), clean)
    clean.replace(path.with_suffix('.pdf'))
    if path.stem == SUPPLEMENT:
        add_appendix_destinations(path.with_suffix('.pdf'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--render', action='store_true')
    args = parser.parse_args()
    # Refresh author masking and the audit metadata without changing main prose.
    subprocess.run(['python3', str(HERE / 'prepare_blinded.py')], check=True)
    # Remove blank canvas margins from the graphic so it fits inside the
    # supplement's one-inch margins without changing any ratings or labels.
    with pikepdf.Pdf.open(HERE / 'stimulus_family_audit_blinded.pdf') as audit:
        audit.pages[0].mediabox = pikepdf.Array([30, 37, 582, 770])
        audit.pages[0].cropbox = pikepdf.Array([30, 37, 582, 770])
        audit.save(HERE / 'stimulus_family_audit_submission.pdf')
    main = (HERE / 'beyond_stimulus_sampling_blinded.qmd').read_text()
    assert main.count(APPENDIX) == 1
    body, materials = main.split(APPENDIX, 1)
    materials = APPENDIX + materials
    materials = materials.replace(APPENDIX, '# Appendix A. Study 1 Message Pair {#apx-study1-messages}', 1)
    materials = materials.replace('# Full Messages From the Reference Family {#apx-reference-family}',
                                  '# Appendix B. Full Messages From the Reference Family {#apx-reference-family}')
    materials = materials.replace('# Example Stimulus Audit {#apx-stimulus-audit}',
                                  '# Appendix C. Example Stimulus Audit {#apx-stimulus-audit}')
    materials = materials.replace('@tbl-certainty-brashness', 'Table 2 of the main manuscript')
    materials, replaced = re.subn(
        r'```\{=latex\}\n\\AddToShipoutPictureFG\*\{.*?\\null\n```',
        lambda _: ('```{=latex}\n\\noindent\\makebox[\\textwidth][c]{%\n'
                   '\\includegraphics[width=\\textwidth,height=8.5in,keepaspectratio]'
                   '{stimulus_family_audit_submission.pdf}%\n}\n```'),
        materials, flags=re.S)
    assert replaced == 1
    materials = re.sub(r'(?m)^(# Appendix [ABC]\. )',
                       lambda match: '```{=latex}\n\\clearpage\n```\n\n' + match.group(1), materials)
    supplement = HERE / (SUPPLEMENT + '.qmd')
    core = supplement.read_text().split(MARKER, 1)[0].rstrip()
    supplement.write_text(core + '\n\n' + MARKER + '\n\n' + materials.rstrip() + '\n')
    # Keep the main text unchanged and direct appendix links to the supplement.
    for anchor in ('apx-study1-messages', 'apx-reference-family', 'apx-stimulus-audit'):
        body = body.replace('(#' + anchor + ')', '(' + SUPPLEMENT + '.pdf#' + anchor + ')')
    submission = HERE / (SUBMISSION + '.qmd')
    submission.write_text(body.rstrip() + '\n')
    print('Prepared supplement source and main-only submission source; original manuscript retained.')
    if args.render:
        render(supplement)
        render(submission)
        for path in (supplement.with_suffix('.pdf'), submission.with_suffix('.pdf')):
            text = subprocess.run(['pdftotext', str(path), '-'], check=True,
                                  capture_output=True, text=True).stdout
            for identifying in ('David Hagmann', 'Zachary Wojtowicz', 'hagmann@ust.hk',
                                'Hong Kong University of Science', 'Massachusetts Institute'):
                assert identifying not in text
            assert '??' not in text
            with pikepdf.Pdf.open(path) as pdf:
                assert '/Author' not in pdf.docinfo
                print(path.name + ': ' + str(len(pdf.pages)) + ' pages; author metadata removed.')


if __name__ == '__main__':
    main()
